#!/usr/bin/env python3
# =============================================================================
# STOP! PLEASE DO NOT HARDCODE CI CONFIGURATIONS IN THIS PYTHON SCRIPT
# =============================================================================
# This script is the Quay CI config generator. It handles merging and
# cartesian expansion of the CI matrix. Do NOT modify this code to update
# test steps, cluster profiles, or to add new OpenShift/Quay versions.
#
# WHERE TO MAKE YOUR CHANGES:
#   1. matrix.yaml — Quay releases, OCP versions, clouds, kind, tiers, source,
#                     env, as, managed_files
#   2. templates/  — job structure (base, clouds/{cloud}, tests/{test});
#                     kind: presubmit renders templates/presubmit/ instead
#   3. generate.py — merge and expansion logic only
#
# Merge order (later layers overwrite earlier):
#   templates/base.yaml (or templates/presubmit/base.yaml for kind: presubmit)
#   templates/sources/<source>.yaml (kind: periodic only)
#   templates/clouds/<cloud>.yaml
#   templates/tests/<test>.yaml
#   templates/presubmit/tests/<test>.yaml (kind: presubmit only, when present)
#   kind settings (periodic cron, or presubmit trigger fields)
#   branch env, then job env / as
#
# Usage:
#   python3 generate.py              # regenerate all CI configs
#   python3 generate.py --dry-run    # preview without writing
#   python3 generate.py --check      # CI gate: verify configs are up to date
"""Generate Quay ci-operator configs from matrix.yaml."""

from __future__ import annotations

import argparse
import copy
import itertools
import re
import sys
from pathlib import Path
from typing import Any

import yaml
from jinja2 import Environment, FileSystemLoader, StrictUndefined, TemplateError
from model import Cell, YamlMap

GENERATOR_DIR = Path(__file__).resolve().parent
TIERS = ("daily", "nightly", "weekly")
SOURCES = ("nightly", "stable")
TIER_INTERVALS = {
    "daily": "@daily",
    "nightly": "@daily",
    "weekly": "@weekly",
}
RELEASE_KEYS = {"branch", "jobs", "env", "layout"}
JOB_KEYS = {
    "kind",
    "tier",
    "source",
    "test",
    "ocp",
    "clouds",
    "env",
    "as",
    "always_run",
    "optional",
    "run_if_changed",
    "skip_if_only_changed",
}
TRIGGER_FIELDS = ("always_run", "optional", "run_if_changed", "skip_if_only_changed")
GENERATED_HEADER = """\
# =============================================================================
# DO NOT EDIT THIS FILE.
#
# It is generated by ci-generator/generate.py. Changes here will be
# overwritten the next time the generator runs, and may be stripped by
# `make ci-operator-config` (determinize-ci-operator) in openshift/release.
#
# Edit these instead:
#   - matrix.yaml   (releases, clouds, tiers, source, branch/job env, as)
#   - templates/    (base, cloud, and test layers)
#   - generate.py   (merge and expansion logic only)
# =============================================================================
"""


def default_output_dir(generator_dir: Path = GENERATOR_DIR) -> Path:
    # When vendored into openshift/release as ci-operator/config/quay/quay/
    # _generator, write configs next to this directory.
    if generator_dir.name == "_generator":
        return generator_dir.parent
    return generator_dir / "out"


def load_yaml(path: Path) -> Any:
    with path.open() as fh:
        return yaml.safe_load(fh)


def jinja_env(templates_dir: Path) -> Environment:
    return Environment(
        loader=FileSystemLoader(str(templates_dir)),
        undefined=StrictUndefined,
        autoescape=False,
        keep_trailing_newline=True,
    )


def render_template(env: Environment, name: str, context: dict[str, str]) -> YamlMap:
    try:
        rendered = env.get_template(name).render(**context)
    except TemplateError as exc:
        raise ValueError(f"failed to render template {name}: {exc}") from exc
    loaded = yaml.safe_load(rendered)
    if loaded is None:
        return {}
    if not isinstance(loaded, dict):
        raise ValueError(f"template {name} must render to a YAML mapping")
    return loaded


def _is_list_of_maps(value: list[Any]) -> bool:
    return bool(value) and all(isinstance(item, dict) for item in value)


def deep_merge(base: Any, overlay: Any) -> Any:
    """Deep-merge overlay onto base. Later values win.

    Mappings recurse. Lists of mappings merge by index. Other lists replace.
    """
    if overlay is None:
        return copy.deepcopy(base)
    if base is None:
        return copy.deepcopy(overlay)
    if isinstance(base, dict) and isinstance(overlay, dict):
        merged: YamlMap = copy.deepcopy(base)
        for key, value in overlay.items():
            if key in merged:
                merged[key] = deep_merge(merged[key], value)
            else:
                merged[key] = copy.deepcopy(value)
        return merged
    if (
        isinstance(base, list)
        and isinstance(overlay, list)
        and _is_list_of_maps(base)
        and _is_list_of_maps(overlay)
    ):
        merged_list: list[Any] = copy.deepcopy(base)
        for index, item in enumerate(overlay):
            if index < len(merged_list):
                merged_list[index] = deep_merge(merged_list[index], item)
            else:
                merged_list.append(copy.deepcopy(item))
        return merged_list
    return copy.deepcopy(overlay)


def _as_str_list(value: Any) -> list[str]:
    if value is None:
        return []
    if isinstance(value, list):
        return [str(item) for item in value]
    return [str(value)]


def _as_mapping(value: Any, where: str) -> YamlMap:
    if value is None:
        return {}
    if not isinstance(value, dict):
        raise ValueError(f"{where} must be a mapping")
    return value


def _parse_github_repo(value: str) -> tuple[str, str]:
    parts = value.split("/")
    if len(parts) != 2 or not parts[0] or not parts[1]:
        raise ValueError(f"repo must be org/repo, got {value!r}")
    return parts[0], parts[1]


def _quay_releases(matrix: YamlMap) -> list[YamlMap]:
    quay = matrix.get("quay")
    if not isinstance(quay, list) or not quay:
        raise ValueError("quay must be a non-empty list of mappings")
    releases: list[YamlMap] = []
    for index, item in enumerate(quay):
        if not isinstance(item, dict):
            raise ValueError(f"quay[{index}] must be a mapping")
        unknown = set(item) - RELEASE_KEYS
        if unknown:
            keys = ", ".join(sorted(unknown))
            raise ValueError(f"quay[{index}] has unknown keys: {keys}")
        releases.append(item)
    return releases


def _quay_version_from_branch(branch: str) -> str | None:
    if branch == "master":
        return None
    prefix = "redhat-"
    if not branch.startswith(prefix):
        raise ValueError(
            f"quay branch {branch!r} must look like 'redhat-X.Y' so the "
            "Quay version can be derived"
        )
    version = branch[len(prefix) :].strip()
    if not re.match(r"^\d+\.\d+$", version):
        raise ValueError(
            f"quay branch {branch!r} must look like 'redhat-X.Y' so the "
            "Quay version can be derived"
        )
    return version


def _job_as_name(job: YamlMap, where: str) -> str | None:
    if "as" not in job:
        return None
    as_name = job.get("as")
    if not isinstance(as_name, str) or not as_name.strip():
        raise ValueError(f"{where}.as must be a non-empty string")
    return as_name


def _job_bool_field(job: YamlMap, key: str, where: str) -> bool | None:
    if key not in job:
        return None
    value = job.get(key)
    if not isinstance(value, bool):
        raise ValueError(f"{where}.{key} must be a boolean")
    return value


def _job_str_field(job: YamlMap, key: str, where: str) -> str | None:
    if key not in job:
        return None
    value = job.get(key)
    if not isinstance(value, str) or not value.strip():
        raise ValueError(f"{where}.{key} must be a non-empty string")
    return value


def expand_cells(matrix: YamlMap) -> list[Cell]:
    defaults = matrix.get("global_defaults") or {}
    if not isinstance(defaults, dict):
        raise ValueError("global_defaults must be a mapping")

    org, repo = _parse_github_repo(str(defaults.get("repo") or "quay/quay"))
    arch = str(defaults.get("arch") or "amd64")
    image_source = str(defaults.get("image_source") or "build")

    cells: list[Cell] = []
    for release_index, release in enumerate(_quay_releases(matrix)):
        branch = str(release.get("branch") or "").strip()
        if not branch:
            raise ValueError(f"quay[{release_index}] is missing branch")
        quay_version = _quay_version_from_branch(branch)
        layout = str(release.get("layout") or "variant")
        if layout not in ("variant", "base"):
            raise ValueError(
                f"quay[{release_index}].layout must be 'variant' or 'base', got {layout!r}"
            )
        branch_env = copy.deepcopy(_as_mapping(release.get("env"), f"quay[{release_index}].env"))
        jobs = release.get("jobs") or []
        if not isinstance(jobs, list):
            raise ValueError(f"quay[{release_index}].jobs must be a list")
        for job_index, job in enumerate(jobs):
            where = f"quay[{release_index}].jobs[{job_index}]"
            if not isinstance(job, dict):
                raise ValueError(f"{where} must be a mapping")
            unknown = set(job) - JOB_KEYS
            if unknown:
                keys = ", ".join(sorted(unknown))
                raise ValueError(f"{where} has unknown keys: {keys}")
            kind = str(job.get("kind") or "periodic")
            if kind not in ("periodic", "presubmit"):
                raise ValueError(f"{where}.kind must be 'periodic' or 'presubmit', got {kind!r}")
            tier_raw = job.get("tier")
            if tier_raw is not None and str(tier_raw) == "presubmit":
                raise ValueError(
                    f"{where}.tier 'presubmit' is retired; use kind: presubmit instead"
                )
            test = str(job.get("test") or "")
            ocps = _as_str_list(job.get("ocp"))
            clouds = _as_str_list(job.get("clouds"))
            if not test or not ocps or not clouds:
                raise ValueError(f"{where} is missing test, ocp, or clouds")
            always_run = _job_bool_field(job, "always_run", where)
            optional = _job_bool_field(job, "optional", where)
            run_if_changed = _job_str_field(job, "run_if_changed", where)
            skip_if_only_changed = _job_str_field(job, "skip_if_only_changed", where)
            source_raw = job.get("source")
            if kind == "periodic":
                tier = str(tier_raw) if tier_raw else ""
                if not tier or tier not in TIERS:
                    raise ValueError(f"{where} periodic job requires tier in {TIERS}")
                set_trigger_fields = [
                    name
                    for name, value in zip(
                        TRIGGER_FIELDS,
                        (always_run, optional, run_if_changed, skip_if_only_changed),
                    )
                    if value is not None
                ]
                if set_trigger_fields:
                    fields = ", ".join(set_trigger_fields)
                    raise ValueError(
                        f"{where} trigger fields ({fields}) are only valid for kind: presubmit"
                    )
                source = str(source_raw) if source_raw else ""
                if not source or source not in SOURCES:
                    raise ValueError(f"{where} periodic job requires source in {SOURCES}")
            else:
                if tier_raw is not None:
                    raise ValueError(f"{where} presubmit job must not set tier")
                tier = None
                if source_raw is not None:
                    raise ValueError(f"{where} presubmit job must not set source")
                source = None
                if run_if_changed is not None and skip_if_only_changed is not None:
                    raise ValueError(
                        f"{where} run_if_changed and skip_if_only_changed are mutually exclusive"
                    )
                if always_run is True and (
                    run_if_changed is not None or skip_if_only_changed is not None
                ):
                    raise ValueError(
                        f"{where} always_run: true cannot be combined with "
                        "run_if_changed or skip_if_only_changed"
                    )
            job_env = copy.deepcopy(_as_mapping(job.get("env"), f"{where}.env"))
            merged_env = {**branch_env, **job_env}
            as_name = _job_as_name(job, where)
            for ocp, cloud in itertools.product(ocps, clouds):
                cells.append(
                    Cell(
                        org=org,
                        repo=repo,
                        branch=branch,
                        quay_version=quay_version,
                        ocp_version=ocp,
                        cloud=cloud,
                        test=test,
                        tier=tier,
                        source=source,
                        arch=arch,
                        image_source=image_source,
                        env=copy.deepcopy(merged_env),
                        as_name=as_name,
                        kind=kind,
                        layout=layout,
                        always_run=always_run,
                        optional=optional,
                        run_if_changed=run_if_changed,
                        skip_if_only_changed=skip_if_only_changed,
                    )
                )
    return cells


def apply_kind_settings(config: YamlMap, cell: Cell) -> YamlMap:
    config = copy.deepcopy(config)
    tests = config.get("tests")
    if not isinstance(tests, list) or not tests or not isinstance(tests[0], dict):
        raise ValueError("generated config is missing tests[0]")
    test = tests[0]
    if cell.kind == "periodic":
        if cell.tier not in TIER_INTERVALS:
            raise ValueError(f"unsupported tier {cell.tier!r}")
        test["cron"] = TIER_INTERVALS[cell.tier]
    elif cell.kind == "presubmit":
        for field_name in TRIGGER_FIELDS:
            value = getattr(cell, field_name)
            if value is not None:
                test[field_name] = value
    else:
        raise ValueError(f"unsupported kind {cell.kind!r}")
    return config


def apply_cell_settings(config: YamlMap, cell: Cell) -> YamlMap:
    config = copy.deepcopy(config)
    tests = config.get("tests")
    if not isinstance(tests, list) or len(tests) != 1 or not isinstance(tests[0], dict):
        raise ValueError("generated config must contain exactly one test")
    test = tests[0]
    if cell.as_name:
        test["as"] = cell.as_name
    if cell.env:
        steps = test.setdefault("steps", {})
        if not isinstance(steps, dict):
            raise ValueError("tests[0].steps must be a mapping")
        env = steps.setdefault("env", {})
        if not isinstance(env, dict):
            raise ValueError("tests[0].steps.env must be a mapping")
        for key, value in cell.env.items():
            env[key] = copy.deepcopy(value)
    return config


def build_config(cell: Cell, templates_dir: Path) -> YamlMap:
    env = jinja_env(templates_dir)
    context = cell.context()
    template_root = "presubmit/" if cell.kind == "presubmit" else ""
    cloud_template = f"{template_root}clouds/{cell.cloud}.yaml"
    if template_root and not (templates_dir / cloud_template).exists():
        # No presubmit-specific cloud layer: share the periodic one instead of
        # forking a byte-identical copy that would need editing twice.
        cloud_template = f"clouds/{cell.cloud}.yaml"
    layers = [render_template(env, f"{template_root}base.yaml", context)]
    if cell.kind == "periodic":
        layers.append(render_template(env, f"sources/{cell.source}.yaml", context))
    layers.append(render_template(env, cloud_template, context))
    layers.append(render_template(env, f"tests/{cell.test}.yaml", context))
    presubmit_test_template = f"{template_root}tests/{cell.test}.yaml"
    if template_root and (templates_dir / presubmit_test_template).exists():
        # Presubmit test layer is a delta on top of the shared periodic test
        # layer, not a byte-identical fork that would need editing twice.
        layers.append(render_template(env, presubmit_test_template, context))
    config: YamlMap = {}
    for layer in layers:
        config = deep_merge(config, layer)
    config = apply_kind_settings(config, cell)
    return apply_cell_settings(config, cell)


class GeneratorDumper(yaml.SafeDumper):
    pass


def _looks_like_number(value: str) -> bool:
    stripped = value.replace(".", "", 1)
    return stripped.isdigit()


def _represent_str(dumper: GeneratorDumper, data: str) -> yaml.Node:
    if "\n" in data:
        return dumper.represent_scalar("tag:yaml.org,2002:str", data, style="|")
    needs_quotes = (
        data == ""
        or data.lower() in {"true", "false", "null", "yes", "no", "on", "off"}
        or _looks_like_number(data)
        or data[0] in "@*&!%|#>,[?'\"{}:"
        or ": " in data
        or data.startswith(" ")
        or data.endswith(" ")
    )
    if needs_quotes:
        style = "'" if data.startswith("@") or data == "*" else '"'
        return dumper.represent_scalar("tag:yaml.org,2002:str", data, style=style)
    return dumper.represent_scalar("tag:yaml.org,2002:str", data)


GeneratorDumper.add_representer(str, _represent_str)


def dump_config(config: YamlMap) -> str:
    dumped = yaml.dump(
        config,
        Dumper=GeneratorDumper,
        default_flow_style=False,
        sort_keys=True,
        allow_unicode=True,
        width=120,
        indent=2,
    )
    if not dumped.endswith("\n"):
        dumped += "\n"
    return GENERATED_HEADER + dumped


def _group_configs(filename: str, group: list[Cell], templates_dir: Path) -> YamlMap:
    file_level: YamlMap | None = None
    tests: list[YamlMap] = []
    seen_as: set[str] = set()
    for cell in group:
        config = build_config(cell, templates_dir)
        cell_tests = config.get("tests")
        if not isinstance(cell_tests, list) or len(cell_tests) != 1:
            raise ValueError("generated config must contain exactly one test")
        test = cell_tests[0]
        as_name = test.get("as")
        if as_name in seen_as:
            raise ValueError(f"duplicate as {as_name!r} in {filename}")
        seen_as.add(as_name)
        rest = {key: value for key, value in config.items() if key != "tests"}
        if file_level is None:
            file_level = rest
        elif rest != file_level:
            raise ValueError(f"incompatible file-level inputs for {filename}")
        tests.append(test)
    assert file_level is not None
    merged = copy.deepcopy(file_level)
    merged["tests"] = tests
    return merged


def _managed_files(matrix: YamlMap) -> tuple[list[str], list[str]]:
    managed = matrix.get("managed_files")
    if not isinstance(managed, dict):
        raise ValueError("managed_files must be a mapping")
    active = managed.get("active")
    if (
        not isinstance(active, list)
        or not active
        or not all(isinstance(item, str) for item in active)
    ):
        raise ValueError("managed_files.active must be a non-empty list of strings")
    if len(set(active)) != len(active):
        raise ValueError("managed_files.active must not contain duplicates")
    retired = managed.get("retired") if managed.get("retired") is not None else []
    if not isinstance(retired, list) or not all(isinstance(item, str) for item in retired):
        raise ValueError("managed_files.retired must be a list of strings")
    overlap = set(active) & set(retired)
    if overlap:
        names = ", ".join(sorted(overlap))
        raise ValueError(f"managed_files: {names} listed in both active and retired")
    return active, retired


def generate_all(
    generator_dir: Path = GENERATOR_DIR,
    matrix_path: Path | None = None,
    templates_dir: Path | None = None,
) -> tuple[list[tuple[list[Cell], str, YamlMap]], list[str]]:
    matrix_path = matrix_path or generator_dir / "matrix.yaml"
    templates_dir = templates_dir or generator_dir / "templates"
    matrix = load_yaml(matrix_path)
    if not isinstance(matrix, dict):
        raise ValueError("matrix.yaml must be a YAML mapping")
    active, retired = _managed_files(matrix)
    groups: dict[str, list[Cell]] = {}
    for cell in expand_cells(matrix):
        groups.setdefault(cell.filename, []).append(cell)
    missing = sorted(set(active) - set(groups))
    extra = sorted(set(groups) - set(active))
    if missing or extra:
        parts = []
        if missing:
            parts.append(f"active but not generated: {', '.join(missing)}")
        if extra:
            parts.append(f"generated but not active: {', '.join(extra)}")
        raise ValueError("; ".join(parts))
    results: list[tuple[list[Cell], str, YamlMap]] = []
    for filename, group in groups.items():
        config = _group_configs(filename, group, templates_dir)
        results.append((group, filename, config))
    return results, retired


def _print_list(results: list[tuple[list[Cell], str, YamlMap]]) -> None:
    headers = ("QUAY", "KIND", "OCP", "CLOUD", "TEST", "TIER", "SOURCE", "FILE", "AS")
    rows: list[tuple[str, ...]] = [headers]
    for group, filename, config in results:
        for cell, test in zip(group, config["tests"], strict=True):
            test_as = test.get("as", cell.test_as)
            rows.append(
                (
                    cell.quay_version or "-",
                    cell.kind,
                    cell.ocp_version,
                    cell.cloud,
                    cell.test,
                    cell.tier or "-",
                    cell.source or "-",
                    filename,
                    str(test_as),
                )
            )
    widths = [max(len(row[i]) for row in rows) for i in range(len(headers))]
    for row in rows:
        print("  ".join(value.ljust(widths[i]) for i, value in enumerate(row)))


def _write_configs(
    results: list[tuple[list[Cell], str, YamlMap]], output_dir: Path, dry_run: bool
) -> None:
    if not dry_run:
        output_dir.mkdir(parents=True, exist_ok=True)
    for _group, filename, config in results:
        text = dump_config(config)
        path = output_dir / filename
        if dry_run:
            print(f"=== {path} ===")
            print(text, end="" if text.endswith("\n") else "\n")
            continue
        path.write_text(text)
        print(f"wrote {path}")


def _check_configs(
    results: list[tuple[list[Cell], str, YamlMap]], retired: list[str], output_dir: Path
) -> int:
    failures = 0
    expected = {filename: config for _group, filename, config in results}
    for filename, config in expected.items():
        path = output_dir / filename
        if not path.exists():
            print(f"missing {path}", file=sys.stderr)
            failures += 1
            continue
        existing = yaml.safe_load(path.read_text())
        if existing != config:
            print(f"stale {path}", file=sys.stderr)
            failures += 1
    for filename in retired:
        path = output_dir / filename
        if path.exists():
            print(f"retired {path}", file=sys.stderr)
            failures += 1
    if failures:
        print(f"{failures} config(s) out of date", file=sys.stderr)
        return 1
    print(f"{len(results)} config(s) up to date")
    return 0


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Generate Quay ci-operator configs from matrix.yaml"
    )
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--dry-run", action="store_true", help="preview YAML without writing")
    mode.add_argument(
        "--check", action="store_true", help="verify generated configs are up to date"
    )
    mode.add_argument("--list", action="store_true", help="show matrix expansion table")
    parser.add_argument("--output", type=Path, help="directory to write (or check) config files")
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    output_dir = args.output.resolve() if args.output else default_output_dir()
    results, retired = generate_all()
    if args.list:
        _print_list(results)
        return 0
    if args.check:
        return _check_configs(results, retired, output_dir)
    _write_configs(results, output_dir, dry_run=args.dry_run)
    return 0


if __name__ == "__main__":
    sys.exit(main())
